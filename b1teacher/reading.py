"""User-supplied reading materials and their original conversation questions."""

from pathlib import Path
import re


def load_text(number):
    source = (Path(__file__).with_name("texts") / f"texto-{number}.txt").read_text(encoding="utf-8-sig")
    # The source repeats the title with a different number above the questions.
    # Keep the original file intact; use its first title as the canonical number.
    title, rest = source.split("\n", 1)
    body = re.split(r"\nTEXTO \d+:", rest, maxsplit=1)[0].strip()
    groups = []
    for line in source.splitlines():
        line = line.strip()
        if line.startswith("Preguntas "):
            groups.append({"label": line, "questions": []})
        elif match := re.match(r"^\d+\. (.+)$", line):
            groups[-1]["questions"].append(match[1])
    questions = [question for group in groups for question in group["questions"]]
    if [len(group["questions"]) for group in groups] != [10, 10, 8]:
        raise ValueError(f"Texto {number}: unvollständiger Fragenkatalog")
    return {"number": number, "title": title, "body": body, "groups": groups, "questions": questions}


READINGS = {number: load_text(number) for number in (3, 4)}
READING_SCENARIOS = {}
for number, reading in READINGS.items():
    for mode, label in (("basico", "Basisteil"), ("ampliado", "Erweiterter Teil")):
        READING_SCENARIOS[f"texto-{number}-{mode}"] = {
            "label": f"Texto {number} · {label}",
            "description": (
                "Alle 28 Originalfragen, ohne zusätzliche Fragen."
                if mode == "basico" else
                "Alle 28 Originalfragen, danach flexible neue Fragen zum Text und deinen Antworten."
            ),
            "opening": reading["questions"][0],
            "instructions": "",
            "reading": reading,
            "mode": mode,
        }


def answered(messages):
    return sum(message["role"] == "user" for message in messages)


def complete(selected, messages):
    return (selected.get("mode") == "basico"
            and answered(messages) >= len(selected["reading"]["questions"]))


def fixed_reply(selected, messages):
    """Basic questions are selected in code, never generated by the model."""
    index = answered(messages)
    questions = selected["reading"]["questions"]
    if index < len(questions):
        return questions[index]
    if selected["mode"] == "basico":
        return "Gracias. Hemos terminado las preguntas del texto. Ahora recibirás tu evaluación."
    return None
